const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
const {startH5TestServer}=require('./h5-built-server.cjs');
(async()=>{
  const server=await startH5TestServer();
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||(process.platform==='darwin'?'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome':'/usr/bin/google-chrome'),args:['--no-first-run']});
  const context=await browser.newContext({viewport:{width:390,height:844},locale:'zh-CN',acceptDownloads:true});
  try {
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(server.url,{waitUntil:'domcontentloaded'});
  const input=page.locator('textarea').first();
  await input.fill('一份没有提交的草稿 📝');
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('textarea').first().inputValue(),'一份没有提交的草稿 📝','draft persists across reload');
  await page.locator('textarea').first().fill('最初的简记 📝');
  await page.getByText('留下',{exact:true}).click();
  assert.ok(await page.getByText('最初的简记 📝',{exact:true}).count()>0,'new note visible');
  await page.getByText('编辑',{exact:true}).first().click();
  await page.locator('textarea').first().fill('后来重新理解的简记 📝');
  await page.getByText('保存',{exact:true}).click();
  assert.equal(await page.getByText('后来重新理解的简记 📝',{exact:true}).count(),1,'edited note visible');
  await page.getByText('设置',{exact:true}).last().click();
  await page.getByText('现代极简',{exact:true}).click();
  await page.reload({waitUntil:'networkidle'});
  assert.ok(await page.getByText('现代极简',{exact:true}).count()>0,'settings remain reachable after theme reload');
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByText('导出完整备份').click()]);
  const fs=require('node:fs');
  const payload=fs.readFileSync(await download.path(),'utf8');
  const backup=JSON.parse(payload);
  const allTexts=Object.values(backup.days).flatMap(day=>day.notes.map(note=>note.text));
  assert.ok(allTexts.includes('后来重新理解的简记 📝'),'export preserves edited note');
  assert.ok(backup.events.some(e=>e.type==='note_edit'),'export preserves old note edit event');
  assert.ok(backup.checksumSha256,'export has checksum');
  await page.locator('.uni-modal__btn').last().click();
  const chooserEvent=page.waitForEvent('filechooser',{timeout:5000});
  await page.getByText('导入备份',{exact:true}).click();
  const chooser=await chooserEvent;
  await chooser.setFiles({name:'错事备份_测试.json',mimeType:'application/json',buffer:Buffer.from(payload)});
  await page.getByText('替换导入',{exact:true}).waitFor({timeout:5000});
  await page.getByText('替换导入',{exact:true}).click();
  await page.waitForTimeout(400);
  await page.getByText('今天',{exact:true}).last().click();
  await page.getByText('后来重新理解的简记 📝',{exact:true}).waitFor({timeout:5000});
  assert.ok(await page.getByText('后来重新理解的简记 📝',{exact:true}).count()>0,'import restores edited note');
  for(let i=0;i<6;i++)await page.locator('.round.primary').click();
  await page.getByText('日历',{exact:true}).last().click();
  await page.locator('.cell.today').click();
  await page.getByText('展开完整历史', {exact:false}).waitFor({timeout:5000});
  assert.equal(await page.locator('.history .event').count(),5,'long history initially collapses to five events');
  await page.getByText('展开完整历史',{exact:false}).click();
  assert.ok(await page.locator('.history .event').count()>5,'full history expands');
  assert.deepEqual(errors,[],'no uncaught browser exceptions');
  console.log('PASS H5 extended: draft, edited notes, theme, JSON export/import and history expand');
  } finally {await context.close();await browser.close();await server.close();}
})().catch(e=>{console.error(e);process.exit(1)});