const {chromium}=require('playwright-core');const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-first-run']});
 const context=await browser.newContext({viewport:{width:390,height:844},locale:'zh-CN'}),page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4177/',{waitUntil:'networkidle'});
 const number=page.locator('.number');
 assert.equal((await number.innerText()).trim(),'—');
 await page.locator('.round.primary').click();
 assert.equal((await number.innerText()).trim(),'1');
 await page.getByText('撤销刚才的修改').click();
 assert.equal((await number.innerText()).trim(),'—');
 await page.locator('.round.primary').click();await page.locator('.round.primary').click();
 assert.equal((await number.innerText()).trim(),'2');
 const note='自动化测试简记：这一天只是测试。';
 await page.locator('textarea').first().fill(note);
 await page.getByText('留下',{exact:true}).click();
 assert.ok(await page.getByText(note).count()>=1,'submitted note must be visible');
 assert.equal(await page.locator('textarea').first().inputValue(),'','composer must clear after submit');
 assert.equal(await page.locator('.header').first().evaluate(e=>getComputedStyle(e).display),'flex','header alignment must be styled');
 await page.reload({waitUntil:'networkidle'});
 assert.equal((await page.locator('.number').innerText()).trim(),'2','count must survive reload');
 assert.equal(await page.locator('.note-body').filter({hasText:note}).count(),1,'note must survive reload without duplicate');
 assert.equal(await page.locator('textarea').first().inputValue(),'','composer must remain empty after reload');
 console.log('COMPOSER_AFTER_SUBMIT',JSON.stringify(await page.locator('textarea').first().inputValue()));
 console.log('HEADER_STYLE',await page.locator('.header').first().evaluate(e=>({display:getComputedStyle(e).display,width:getComputedStyle(e).width,justify:getComputedStyle(e).justifyContent,brand:e.querySelector('.brand')?.getBoundingClientRect().toJSON(),date:e.querySelector('.small-date')?.getBoundingClientRect().toJSON()})));
 await page.waitForTimeout(2400);
 await page.screenshot({path:'qa-today-filled.png',fullPage:true});
 await page.getByText('日历',{exact:true}).last().click();
 await page.getByText('日历',{exact:true}).first().waitFor();
 await page.screenshot({path:'qa-calendar.png',fullPage:true});
 await page.getByText('统计',{exact:true}).last().click();
 await page.screenshot({path:'qa-stats.png',fullPage:true});
 await page.getByText('设置',{exact:true}).last().click();
 await page.screenshot({path:'qa-settings.png',fullPage:true});
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByText('导出完整备份').click()]);
 const fs=require('node:fs'),backup=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 assert.equal(backup.days[Object.keys(backup.days)[0]].count,2,'backup must preserve count');
 assert.ok(backup.events.length>=4,'backup must preserve history');
 assert.ok(backup.checksumSha256,'backup must include integrity checksum');
 await page.getByText('确定',{exact:true}).last().click();
 await page.setViewportSize({width:320,height:640});
 await page.getByText('今天',{exact:true}).last().click();
 const docWidth=await page.evaluate(()=>document.documentElement.scrollWidth);
 assert.ok(docWidth<=321,'320px viewport must not overflow horizontally: '+docWidth);
 await page.screenshot({path:'qa-small-screen.png',fullPage:true});
 assert.deepEqual(errors,[]);console.log('PASS Chrome H5 flow: count, undo, repeat, note, calendar, stats, settings; errors=0');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)})